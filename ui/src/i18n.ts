// ── Locale state ──────────────────────────────────────────────────────────────

let _locale: Locale = (() => {
  const s = localStorage.getItem('gtfs-locale');
  return s === 'en' ? 'en' : 'tr';
})();

export function getLocale(): Locale { return _locale; }


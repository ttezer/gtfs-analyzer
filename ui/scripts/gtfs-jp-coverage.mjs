// Generate the UI's GTFS-JP coverage contract from the audited provision
// inventory. The TSV is the denominator; the UI must not carry a hand-written
// `true` that can drift away from the MLIT mapping.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const inventoryPath = fileURLToPath(new URL('../../spec-audit/gtfs_jp_provisions.tsv', import.meta.url));
const outputPath = fileURLToPath(new URL('../src/gtfs-jp-coverage.generated.ts', import.meta.url));
const requiredColumns = [
  'provision_id', 'profile', 'strength', 'automation', 'rule_ids', 'source', 'note',
  'source_document', 'source_version', 'audited_on', 'page_anchor',
];

function parseInventory() {
  const [header, ...lines] = readFileSync(inventoryPath, 'utf8').trimEnd().split(/\r?\n/);
  const columns = header.split('\t');
  if (columns.join('\0') !== requiredColumns.join('\0')) {
    throw new Error(`unexpected GTFS-JP inventory columns: ${columns.join(', ')}`);
  }
  return lines.map((line, index) => {
    const values = line.split('\t');
    if (values.length !== columns.length) {
      throw new Error(`inventory row ${index + 2} has ${values.length} columns, expected ${columns.length}`);
    }
    return Object.fromEntries(columns.map((column, i) => [column, values[i]]));
  });
}

const rows = parseInventory();
const provisions = rows
  .filter((row) => row.automation === 'rule')
  .map((row) => ({
    provisionId: row.provision_id,
    profile: row.profile,
    ruleIds: row.rule_ids.split(';').map((id) => id.trim()).filter(Boolean),
    source: row.source,
    sourceDocument: row.source_document,
    sourceVersion: row.source_version,
    auditedOn: row.audited_on,
    pageAnchor: row.page_anchor,
  }));

const unmatchedMachineProvisions = rows
  .filter((row) => row.automation === 'rule' &&
    row.rule_ids.split(';').every((id) => !id.trim()))
  .map((row) => row.provision_id);

if (provisions.length === 0) throw new Error('GTFS-JP inventory has no machine rule provisions');

const generated = `// Generated by ui/scripts/gtfs-jp-coverage.mjs — do not edit by hand.\n\n` +
  `export const GTFS_JP_AUTOMATED_PROVISIONS = ${JSON.stringify(provisions, null, 2)} as const;\n\n` +
  `export const GTFS_JP_UNMATCHED_MACHINE_PROVISIONS = ${JSON.stringify(unmatchedMachineProvisions)} as const;\n\n` +
  `export const GTFS_JP_AUTOMATED_COVERAGE_COMPLETE =\n` +
  `  GTFS_JP_AUTOMATED_PROVISIONS.length > 0 &&\n` +
  `  GTFS_JP_UNMATCHED_MACHINE_PROVISIONS.length === 0 &&\n` +
  `  GTFS_JP_AUTOMATED_PROVISIONS.every((provision) => provision.ruleIds.length > 0);\n`;

const check = process.argv.includes('--check');
if (check) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== generated) {
    console.error('drift: ui/src/gtfs-jp-coverage.generated.ts is stale — run `npm run gtfs-jp:coverage`');
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, generated);
  console.log(`wrote ui/src/gtfs-jp-coverage.generated.ts (${provisions.length} machine rule provisions)`);
}

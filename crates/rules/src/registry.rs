    /// AUTHORITY tablosu her RULES kuralını birebir kapsamalı (drift yok):
    /// eksik yok, yetim yok, mükerrer yok. Otorite SSOT bütünlüğünün temeli.
    #[test]
    fn authority_covers_all_rules() {
        use std::collections::HashSet;
        let rule_ids: HashSet<&str> = RULES.iter().map(|r| r.id).collect();
        let auth_ids: HashSet<&str> = AUTHORITY.iter().map(|&(k, _)| k).collect();
        assert_eq!(AUTHORITY.len(), auth_ids.len(), "AUTHORITY'de mükerrer id");
        let missing: Vec<&str> = rule_ids.difference(&auth_ids).copied().collect();
        let orphan: Vec<&str> = auth_ids.difference(&rule_ids).copied().collect();
        assert!(missing.is_empty(), "AUTHORITY'de eksik kural(lar): {missing:?}");
        assert!(orphan.is_empty(), "AUTHORITY'de yetim giriş(ler): {orphan:?}");
    }

    /// Otorite bütünlüğü çekirdek değişmezi: hiçbir kural `Spec` sınıfındayken
    /// authority_source ≠ GtfsSpec olamaz. Faz 3 sınıfları düzeltene dek mevcut
    /// ihlaller `SPEC_AUTHORITY_ALLOWLIST`'te tutulur (warn-modu); liste Faz 4'te boşalır.
    #[test]
    fn spec_class_requires_gtfs_spec_authority() {
        let violations: Vec<&str> = RULES
            .iter()
            .filter(|r| r.rule_class == RuleClass::Spec)
            .filter(|r| authority_source(r.id) != AuthoritySource::GtfsSpec)
            .map(|r| r.id)
            .filter(|id| !SPEC_AUTHORITY_ALLOWLIST.contains(id))
            .collect();
        assert!(
            violations.is_empty(),
            "Spec sınıfı ama authority≠GtfsSpec ve allowlist'te değil: {violations:?}"
        );
    }


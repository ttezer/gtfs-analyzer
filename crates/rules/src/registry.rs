/// Analytics + Geo → R3+R4+R9
const VA_GEO: &[ReportId] = &[R2, R3, R4, R5, R9];

// Erişilebilirlik eki (R7)
/// Interop + (KRİTİK|YÜKSEK) + Accessibility → R1+R7+R8
const VI_K_ACC: &[ReportId] = &[R1, R2, R5, R7, R8, R9];
/// Analytics + Accessibility → R3+R7+R9
